        <td width="426" class="text"><p class="style3">CONGRESSES OF KURDISTAN DEMOCRATIC PARTY (1946-1999) </p><br>
            In all its congresses, which have always convened publicly, and irrespective of any subjective or objective circumstances, the Kurdistan Democratic Party (KDP) has applied the democratic principles of voting, respecting the views of the majority as well as the minority and freedom of expressing opinion in elections, decision making, naming representatives and laying down the party statute. <br>
  <br>
  <strong>First Congress </strong> (foundation congress) <br>
  <br>
            The first congress of the party convened in Baghdad in 1946, thanks to the immortal Barzani's initiative in the wake of world war II and the emergence and development of world liberation movements and democratic trends. Indeed, the peculiar circumstances of the Kurdish people necessitated the existence of a patriotic, nationalist and democratic party capable of leading the movement of the Kurds. At this congress, the party's statute was formulated and the immortal Barzani was elected the first chairman of the Party. <br>
  <br>
  <strong>Second Congress </strong><br>
  <br>
            The Second Congress convened in Baghdad in march 1951 at a time when some of the party's leadership members had been arrested by the Iraqi regime and the party members were subjected to arrest and chasing under martial laws and the party ranks were beginning to disintegrate. The congress was devoted to resolving such problems. <br>
  <br>
  <strong>Third Congress </strong><br>
  <br>
            The Third Congress convened in Kirkuk on January 26, 1953 with the view of reinforcing the party ranks. It was in this congress that the party's name was changed from the Kurdish Democratic Party into the Kurdistan Democratic Party-Iraq. It was also decided to form a number of Kurdish popular and professional organisations, and the name of the party's organ was changed from Rizgari to Khebat. <br>
  <br>
  <strong>Forth Congress </strong><br>
  <br>
            This congress convened in Baghdad, October 4-7, 1959 following the demise of the Iraqi Monarchy amidst considerable political freedom. The immortal Barzani and his comrades had already returned home from the Soviet exile. This Congress is considered to be one of the most important congresses of the KDP and the first one to be attended by Mustafa Barzani. In this congress, the KDP was able to rid itself of the ideological conflicts and adopt a nationalist and progressive method. <br>
  <br>
  <strong>Fifth Congress </strong><br>
  <br>
            The Fifth Congress convened at the KDP's Headquarter in Baghdad in early May 1960. It convened following the announcement of the political parties' law. This was the first time for the KDP to be officially permitted to conduct its activities publicly and legally. <br>
  <br>
  <strong>Sixth Congress </strong><br>
  <br>
            This congress convened in Qala Diza in early July 1964. It was devoted to the conflicts, within the leadership, brought about by the negotiations that had taken place between the Kurdish movement and the Iraqi regime. This congress realised its objectives successfully. <br>
  <br>
  <strong>Seventh Congress </strong><br>
  <br>
            The Seventh Congress convened in Galala on November 15, 1966 in the wake of June 29 agreement. The KDP seized the chance to further unify its ranks. <br>
  <br>
  <strong>Eighth Congress </strong> (The Congress of peace and national unity) <br>
  <br>
            This congress convened in Naw Pirdan on July 1, 1970 almost four months after March 11 Agreement with the objective of enhancing the ranks of the Party, the people of Kurdistan and that of Iraqi people as whole. This congress is considered to be a very important one with regard to organisation, maximum attendance by Party members, guests, friends of the Party and the Kurdish people as well as realisation of the congressional objectives. 

