  <strong>Ninth Congress </strong><br>
  <br>
            This congress convened on the Iraqi-Iranian-Turkish borders, December 4-13, 1979. It was the first congress after the death of its leader Barzani. It was also the first congress after the 1975 conspiracy. The congress was considerably successful in reorganising the parties ranks and re-establishment of the May Revolution institutions. It was in this congress that Mr. Massoud Barzani was elected the chairman of the KDP; in his words, &ldquo;this was the most difficult and burdensome congress&rdquo;. <br>
  <br>
  <strong>Tenth Congress </strong><br>
  <br>
            This congress of the KDP convened in the district of Margewer, December 12-17, 1989. It was in the aftermath of the well documented barbaric chemical attacks against the Kurds and the Anfal operations by the Iraqi regime resulting in the annihilation of tens of thousands of helpless people, displacement and deportation of a similar number of innocent civilians with devastation of more than 4.500 Kurdish villages and townships. In this congress heavy emphasis was laid on unifying the party ranks, and consolidating the Kurdistan Front and popular unity. 
