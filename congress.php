            <strong>Eleventh Congress </strong><br>
            <br>
            This congress was convened in Arbil on August 16th 1993 against the background of new and rapid developments in Kurdish politics and the region. Over two third of Iraqi Kurdistan was controlled by the Kurds and an elected Kurdish National Assembly with a Regional Government was running the affairs of the Kurds. In the 11th Congress, a number of other political parties reunited with the KDP and further consolidated and strengthened the Party's position amongst the Kurdish nation. <br>
