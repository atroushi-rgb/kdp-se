  <strong>Twelfth Congress </strong><br>
  <br>
         Twelfth congress: it was held on 6-14/10/1999 in the city of Erbil, the capital of the Kurdistan Region with the participation of 1473 representatives. President Barzani was re-elected as the President and Ali Abdulla as his Deputy.
         
         Thirteenth congress: The congress was convened on 11-18 December 2010 in Erbil and was attended by 1500 representatives. President Barzani was re-elected and Nechirvan Barzani became the Deputy President. . </p></td>
     
<br>
  <strong>13th Congress </strong><br>
  <br>
         The party’s 13th congress was held in December 2010 in Erbil, capital of Kurdistan, under the banner of Renewal, Justice and Coexistence. The congress re-elected Masoud Barzani as president of the party and welcomed the appointment of Nechirvan Barzani as vice president. </p></td>
      
