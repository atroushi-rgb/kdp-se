        <td width="426" class="text"><p class="style3">KDP'S YOUTH POLICY</p>
 




Naturally, the youths of Kurdistan are recognised as the asset of the Kurds. They are the next generation to lead and continue with a fight for peace, liberty and democracy.<br>
<br>
 

KDP believes in the next generation and the youth of today. Securing their future is a priority and providing all the means to the youth for education is given paramount importance. Furthermore, promoting recreation activities and adaptation to developing technologies are also encouraged. The youth are been taught to build self- confidence and trust in themselves. At the same time to promote unity, co-operation and team work amongst their partners and colleagues. <br>
<br>


The KDP's Student and Youth Union actively is working with the youth to encourage and attract more students to enlist for higher and post graduate studies. Scholarships to third countries were secured in the past for many students who are now in a position to contribute in the re-building Kurdistan through various means. <br>
<br>

Many youths in Kurdistan have lost a parent, or both during the campaigns of genocide and calamities befallen on Kurds. KDP as an obligation and honouring the martyrs of liberation movement provides all the necessary assistance to the martyrs' children. They are given priorities and certain privileges at the beginning of their education life to its completion and employment. <br>
<br>

Sports, arts and cultural activities are other fields, which are being developed, and the youth are encouraged to be involved in such activities. Many professional singers, musicians and sportsmen began their profession initially as an interest and hobby within these institutions. Through these clubs many hidden talents of the youth are discovered. <br>
<br>

An educated, dynamic, healthy and sound-minded youth contributes immensely to the building of a modern and developing society. <br>
<br>




We will ensure that young Kurds are properly recognized as one of our Nation's greatest assets. The greater fitness of youth to accept change and will lead the way for Kurdistan. <br>
<br>

Young people should be able to find position that meet their expectations. 
And they should be able to look forward to setting up a family and living in a secure and stable Kurdistan. 

Essentially, young Kurds should be able to look forward to accept a nation in which living standards and opportunities are good now. 

For many young people, our society does still provide the chance to succeed. Many young people feel divided. They feel their political heads have given up on them. They see little cause for optimism. We work hard on it and we will ensure that young people will feel the different in near future. 

KDP will seek to secure that peace, freedom, democracy and justice are the main features of our policy. 

The Kurdistan Democratic Party believe that one of the first priorities is to provide a climate in which young Kurds can plan their futures with hope, confidence and security. 

As the most important aim of a KDP, we want to provide meaningful life opportunities for all. 

We give young Kurds an effective voice in KDP and ensure that their interests and needs are continually at the frontage of party decision forming. 

Fundamentally, we want to restore young people's faith in our society, its institutions and the democratic process that our party will march on always. 

The Kurdistan Democratic Party recognize the considerable involvement of young people in sport and recreation activities. 

The Kurdistan Democratic Party has a long and proud record of promoting and supporting Kurdish culture and the arts. </td>
