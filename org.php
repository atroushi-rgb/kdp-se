Kurdistan Democratic Party was established on 16th August 1946 under the leadership of the late Mustafa Barzani. <br><br>

 

The leadership and organisational structure of the Party is as following: <br><br>
President <br>

 


Vice President <br>
 

Political Bureau <br>
 

Central Committee <br><br>
 

 


The structure and party administration is divided into regions or branches known as (liq) districts as (nawcha), local organisations as (rek-khraw) and cells as (shana). Eack liq is subdivided into nawchas; nawchas into rek-khraws and rek-khraws into shanas. <br>
