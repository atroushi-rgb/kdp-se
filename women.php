        <td width="426" class="text"><p class="style3">KURDISTAN WOMEN UNION (KWU)</p>
        Kurdistan Women Union (KWU) is the KDP's women organisation division which advocates for the rights of women and interests within the party and society. Ever since its formation in 1952, the KWU has actively participated in the Kurdish national struggle and fought for the realisation of human and democratic rights for the people of Kurdistan.<br>
<br>
<img src="women.jpg" width="400" height="225"><br><br>
The organisation is engaged on two fronts against oppression and discrimination. In addition, taking an active role in the resistance movements of the KDP against repression of the Kurds by successive Iraqi regimes. KWU has attempted to end discrimination and prejudices within the male dominated Kurdish society. <br><br>

The Union held its last conference called "Martyr Layla Qassim" on February 20-22, 1992 under the slogan: <br>

Peace, Freedom, Equality, and Justice <br>

There were 177 members of active women and from new generation who attended the conference representing all governorates of Kurdistan. The participant members, represented all aspects of the Kurdish society such as women peshmergas, doctors, teachers, lawyers and civil servants. The conference procedures were in a democratic manner. The opening session commenced with a speech from the provisional secretariat of KWU. It was attended by many guests and influential people such as Mr. Nechirvan Barzani and numerous political and public figures. The conference received many messages of greetings and solidarity from women organisations within Kurdistan and world-wide. The conference democratically elected 21 member Executive Committee who in turn elected a Secretariat of nine members. The important decisions of the "martyr Layla Qassism" conference by Kurdistan Women Union are:<br> 

Participation in the memory of the martyrs of Halabja, reconstruction of Kurdistan and the development of Kurdish Community.<br> 

The Union has also decided that women must have active role in all social aspects in Kurdistan. <br>

The conference also clearly stated that the families and relatives of martyrs and victims of Anfals must be honoured and provided assistance. <br>

The social and health conditions of Kurdistan women and children must be upgraded. <br>

Cultural activities should be given importance and developed amongst communities. <br>

The conference also demanded the lift of UN embargo imposed on Iraqi people. <br>

Support a peaceful solution to the Kurdish issue. <br>

Sending appreciation and gratitude letters to all the governments who have sent aids and assistance to the Kurds and asking these governments to participate or contribute in the projects of reconstruction in Kurdistan. <br>

Requesting the UN Security Council to change the latitude 36 to 34 in order to bring all the Iraqi Kurds under protection and mandate of the UN. <br>

Sending appreciation and gratitude letters to all the NGO's of European countries, which have sent medicines, food and essential materials for the people of Kurdistan. <br>

The conference decided to have departments of arts (music and painting...etc.) and sport teams in all the branches of the union. <br>

The following committees established in the conference: 

Committee of the Internal Program <br>

Committee of the Finance <br>

Committee of the Martyrs <br>

Committee of the Anfals and Displaced <br>

Committee of the Human Rights <br>

Committee of the Information and Education <br>

Committee of Public Relation <br>

Committee of Health and Social affairs for maternity and childhood and the economical conditions of the Kurdish families. <br>

The Secretariat consists of four teachers, two physicians, an accountant, and a housewife. <br>

The organisation has branches in the Kurdish cities of Arbil, Duhok, Sulaimania and Kirkuk. The KWU has more than ten thousand members.<br> 

Social Projects <br><br>

The KWU has established a sewing factory to create jobs for women in Arbil. The Union also operates a social and health care centre to extent basic essential services to poor families. Other projects include the opening of a recreation facility and playground with the assistance of International NGO's to engage children with physical activities after school. <br><br>

Educational programs have been created through meetings and publications to explain the discrimination and injustices endured by women in the society. The Union has sent delegations to a number of European countries to develop relations with women organisations, seek humanitarian assistance for female victims in Kurdistan, and exchange experience on administration and organisation. Future aspirations include opening nursing schools, orphanages for the Anfal children who have lost their parents and obtaining more school supplies. Mrs. Shirien Amedy not only heads the Union but also is a leading member in the Central Committee of the Kurdistan Democratic Party. Other members of the KWU also hold public offices which include two seats in the Kurdistan National Assembly (Parliament), General Director Ministry of Health, General Director of Social Affairs and General Director of Municipality and Tourism Ministry. <br><br>

Women make great strides in Kurdistan <br><br>

With the great changes in man's life, civilisation has developed with balanced relations between men and women contribute substantially towards social progress and establishment of a better new life. A close consideration of the Kurdish social life reveals that apart from all the social and political responsibilities they share with men, Kurdish women have extensively and actively participated in agricultural and industrial production, which characterises rural and urban lives respectively. Kurdish women have contributed generously to construction and reconstruction through ceaseless efforts.<br><br> 

New Kurdish Women <br><br>

Owing to the economic, political and social transformations, Kurdish women have made great progress. Today, Kurdish women are members of parliament, ministers, teachers, engineers, lawyers, labourers and other professional bodies. <br><br>

Women and Sacrifice <br><br>

A review of the history of our nation reveals the fact that Kurdish women have offered many sacrifices for the Kurdish cause. Women like Khanzad and Hapsakhan have played effective roles in the Kurdish struggle. In the struggle against the Baghdad regime, Kurdish women as mothers, sisters, daughters, wives, fiancees have offered considerable sacrifices. Layla Qassim, who was hanged by Iraqi regime, symbolises Kurdish steadfastness and forbearance. Tens of Kurdish women carried arms and faced martyrdom in the glorious Uprising of 1991. <br>
<br>

Kurdish women Organisations and Activities <br><br>

Today there are several women organisations in Kurdistan with various types of activities. Mrs. Shirien Amedy is the head of the Kurdistan Women Union. Today, Kurdish women are vigilant and from all walks participate side by side with men to bring about progressive transformations and to preserve popular achievements. <br><br>

Seven women are members of the present Kurdish Parliament. Compared with the neighbouring countries, Kurdish women are far more active in the affairs of their people. They are now free and accorded due respect. Women's role in the Parliament is to struggle for preserving popular achievements, consolidating the democratic experiment in Kurdistan and securing the legitimate rights for the Kurds which is available in the civilised world. There are Kurdish women who take part in the cabinet of the Kurdistan Regional Government. A visit to the courts of justice in Kurdistan reveals that numbers of female lawyers are constantly on the increase. A female lawyer is well acquainted and experienced in the uphill struggle and social injustice facing women in the past. Therefore she is in a better position to comprehend such problems which may still exists and it is only natural for a female lawyer to take on these cases. Kurdish women play an important role in bringing up the new generation as well as in numerous positions in the community. The Iraqi regime used to repress women but today all doors of opportunities are open for women to adopt various tasks in free Kurdistan. They have come out to contribute enthusiastically to daily life. Kurdish women engineers participate in reconstructing Kurdistan, which has been devastated by Iraqi regime. Kurdish women play remarkable roles in Kurdistan theatres and arts. Kurdistan, in the past, the theatre suffered from shortage of female cadres because the society viewed women differently and in seclusion. <br><br>

Today, women actively participate in all aspects of working life in Kurdistan as mentioned above. Contrast to previous injustice and discrimination, women are considered to be half of the society and (mother to the other half) as stated by the KDP leader Massoud Barzani. Their activities in the fields of reconstructing Kurdistan are clearly visible. Perhaps by far the most important role they have taken upon themselves is to being mother to the young generation and bringing them up in the Kurdish way in order to preserve its identity for future, which has been constantly under threat. </td>
