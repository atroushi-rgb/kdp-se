            <p align="left"> The KDP combines democratic values and social justice to form a system whereby everyone in Kurdistan can live on equal basis with great emphasis given to rights of individuals and freedom of expression. <br />
              <br />
              In all of the KDP's General Congresses, the party reviews the rapid developments in the world and in the region re-assessing the strategies and policies to be adopted in order to enable the Party to serve the Kurdish nation and other communities in Iraqi Kurdistan more efficiently. Also with the aim to promote the Kurdish cause in a peaceful manner in line with international rules and norms in conduct of politics and diplomacy. <br />
              The KDP, as the senior coalition political partner in the Kurdish Regional Government and Kurdish National Assembly, is at the forefront in defending these sacred establishments which symbolises &ldquo;peace, liberty and democracy&rdquo; for the Kurdish people, achieved with the blood of tens of thousands of martyrs. Such institutions are the hopes of brighter future for millions of Kurds world-wide. For the last five decades KDP has kept the torch of national struggle burning and gathering around itself the majority of Kurdish people. After fifty-four years of its existence, today KDP by far the largest and strongest Kurdish political entity in the region; respected by friends and feared by foes. <br />
              <br />
              The Kurds have high expectations from the KDP. To a large extend the promises and projects of the party are being delivered. However KDP believes that there is much to be done in order to serve the nation. It is also aware of the difficulties and obstacles before its path and wary of ploys against the Kurds and the party itself. Bitter experiences of the past of abandonment and betrayal are always fresh in Kurdish minds. KDP befriends those who respect and value such friendship and such relations to be based on mutual respect and interest. At times KDP has paid dearly for these principles. <br />
              <br />
              KDP strongly believes in internal peace and regional stability. The party leadership has employed every tool at its disposal and has explored every avenue to settle the internal dispute with the PUK (Patriotic Union of Kurdistan). <br />
              <br />
              Preservation of unity and integrity of Iraq is an aim of the party. The full rights of the Kurds for self-determination can only be achieved through peaceful means in a democratic, pluralist and federal Iraq. It also believes that the rights of the Kurds in neighbouring countries can only be guaranteed through democratic and peaceful means within the boundaries of states in which the Kurds live. Furthermore, the KDP has always adopted the policy of non-intervention in the internal affairs of neighbours. <br />
              <br />
              KDP and its strong position amongst the Kurds, minorities and opposition groups in Iraq have always been viewed as a bonding element for unity, fraternity and stability amongst people of Iraq. It has always defended the rights of other oppressed people in the world and has strongly protested the injustices. It has firmly supported the demands of the Palestinian people throughout their struggle.<br />
              <br />
              In 1950's till late 70's, KDP was the only voice of Kurdish people internationally. Since KDP believes in multi-party system, today there are tens of Kurdish and non-Kurdish political groups exercising their democratic rights in Iraqi Kurdistan. KDP is determined to consolidate these achievements and strengthen the experience of democracy in our society. <br />
